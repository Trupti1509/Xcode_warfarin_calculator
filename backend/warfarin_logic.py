"""
Xcode Life Warfarin Dosing Calculator logic.

Scientific scope
----------------
- Adults only (V1 input validation: 18-120 years)
- Stable maintenance-dose estimation
- Target INR 2.0-3.0
- IWPC clinical-only or IWPC pharmacogenetic equation
- CPIC 2017 genotype/ancestry considerations layered transparently on top

Important design rules
----------------------
1. Never convert an unavailable genetic marker into a reference call.
2. Uploaded Xcode Warfarin_Input CSVs are evaluated marker-by-marker.
3. Manual PGx values must be explicit reported results; *1 must not mean "not tested".
4. For the Black/African ancestry pathway, CYP2C9 *5/*6/*8/*11 coverage must be known
   before the PGx equation is used; otherwise use the clinical IWPC equation.
5. CPIC percentage modifiers are displayed separately from the IWPC base estimate.
   V1 does not silently stack multiple modifiers into one falsely precise final dose.
6. The IWPC algorithm predicts a point estimate in mg/week (and average daily equivalent in mg/day).
   No arbitrary percentage-based "safe range" (e.g. ±20%) is generated.
"""

